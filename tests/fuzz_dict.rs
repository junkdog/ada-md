//! F-013: `fuzz/markdown.dict` names a fence tag for every grammar ada ships, so `print`,
//! `render` and `session` reach each one without spelling its name. The tags are generated
//! from `highlight::syntaxes()`, so the list follows the set: this test fails when the block
//! between [`BEGIN`] and [`END`] differs from what the set gives, and rewrites it when run as
//!
//! ```zsh
//! ADA_BLESS=1 cargo test --test fuzz_dict
//! ```

use std::path::Path;

use ada::doc::{self, BlockKind};
use ada::highlight::{self, ALIASES};
use syntect::parsing::SyntaxReference;

const DICT: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/fuzz/markdown.dict");
const BEGIN: &str = "# Fence tags, one per grammar (F-013): generated by tests/fuzz_dict.rs, \
                     ADA_BLESS=1 cargo test --test fuzz_dict rewrites them";
const END: &str = "# end of the generated fence tags";

/// Tags people write that aren't a grammar's first token, beside the aliases (`c++`, where C++
/// gives `cpp`). Each must reach a grammar.
const SPELLINGS: &[&str] = &["c++"];

/// The language a fence tagged `tag` gets, as ada parses it.
fn fence_language(tag: &str) -> Option<Box<str>> {
    let text = format!("```{tag}\nx\n```\n");
    match &doc::parse(&text).blocks.first()?.kind {
        BlockKind::Code(code) => code.lang.clone(),
        _ => None,
    }
}

/// A fence tag that highlights as `syntax`: its first extension a fence can name, or its name.
fn tag_for(syntax: &SyntaxReference) -> Option<&str> {
    let reaches = |tag: &str| {
        fence_language(tag).as_deref() == Some(tag)
            && highlight::find_syntax(tag).is_some_and(|s| std::ptr::eq(s, syntax))
    };
    syntax
        .file_extensions
        .iter()
        .map(String::as_str)
        .chain([syntax.name.as_str()])
        .find(|&tag| reaches(tag))
}

/// A dictionary entry: the bytes in quotes, anything but printable ASCII as `\xNN`.
fn entry(text: &str) -> String {
    let mut out = String::from("\"");
    for b in text.bytes() {
        match b {
            b'"' | b'\\' | ..=0x1f | 0x7f.. => out.push_str(&format!("\\x{b:02x}")),
            _ => out.push(char::from(b)),
        }
    }
    out.push('"');
    out
}

/// The generated block, [`BEGIN`] and [`END`] included.
fn block() -> String {
    let mut tags: Vec<&str> = Vec::new();
    let mut unreached = Vec::new();
    for syntax in highlight::syntaxes().syntaxes() {
        match tag_for(syntax) {
            Some(tag) => tags.push(tag),
            None if syntax.name == "Plain Text" => {}
            None => unreached.push(syntax.name.as_str()),
        }
    }
    for &(alias, _) in ALIASES {
        if !tags.contains(&alias) {
            tags.push(alias);
        }
    }
    for &tag in SPELLINGS {
        assert!(
            highlight::find_syntax(tag).is_some(),
            "{tag} reaches no grammar"
        );
        if !tags.contains(&tag) {
            tags.push(tag);
        }
    }
    let mut out = format!("{BEGIN}\n");
    if !unreached.is_empty() {
        out += &format!("# no fence tag reaches: {}\n", unreached.join(", "));
    }
    for tag in tags {
        out += &entry(&format!("```{tag}\n"));
        out.push('\n');
    }
    out += END;
    out.push('\n');
    out
}

#[test]
fn markdown_dict_names_every_grammar() {
    let dict = std::fs::read_to_string(DICT).expect("fuzz/markdown.dict");
    let expected = block();
    let current = dict.find(BEGIN).map(|start| {
        let end = dict[start..]
            .find(END)
            .map(|e| start + e + END.len() + 1)
            .expect("the generated block's end line");
        start..end.min(dict.len())
    });
    if current
        .clone()
        .is_some_and(|range| dict[range] == *expected)
    {
        return;
    }
    if std::env::var_os("ADA_BLESS").is_some() {
        let updated = match current {
            Some(range) => format!("{}{expected}{}", &dict[..range.start], &dict[range.end..]),
            None => format!("{dict}{expected}"),
        };
        std::fs::write(Path::new(DICT), updated).expect("write fuzz/markdown.dict");
        return;
    }
    panic!(
        "fuzz/markdown.dict's fence tags don't follow the syntax set; \
         ADA_BLESS=1 cargo test --test fuzz_dict rewrites them:\n{expected}"
    );
}
